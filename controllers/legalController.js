const prefersHtml = (req) => {
  return (
    req.query.format === 'html' ||
    (req.headers.accept &&
      req.headers.accept.includes('text/html') &&
      !req.headers.accept.includes('application/json'))
  );
};

// Check if request prefers plain text format
